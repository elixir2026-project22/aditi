
from aditi.api.schemas.pathway_requests import (
    PathwayDefinitionRequest,
)
from aditi.domain.pathways import (
    Metabolite,
    Pathway,
    PathwayGraph,
    Reaction,
    ReactionParticipant,
)


class PathwayGraphBuilder:
    """
    Converts validated API pathway definitions into domain graphs.

    Request-local identifiers are used to resolve reaction
    participants. BiologicalEntity identities remain independently
    generated by the domain model.
    """

    def build(
        self,
        definition: PathwayDefinitionRequest,
    ) -> PathwayGraph:
        """Build a biological pathway graph from an API definition."""

        if not isinstance(definition, PathwayDefinitionRequest):
            raise TypeError(
                "Pathway graph builder requires a "
                "PathwayDefinitionRequest."
            )

        metabolites = {
            item.id: Metabolite(
                name=item.name,
                chemical_formula=item.chemical_formula,
                charge=item.charge,
            )
            for item in definition.metabolites
        }

        reactions: list[Reaction] = []

        for item in definition.reactions:
            reactants = tuple(
                ReactionParticipant(
                    metabolite=metabolites[participant.metabolite_id],
                    coefficient=participant.coefficient,
                )
                for participant in item.reactants
            )

            products = tuple(
                ReactionParticipant(
                    metabolite=metabolites[participant.metabolite_id],
                    coefficient=participant.coefficient,
                )
                for participant in item.products
            )

            reactions.append(
                Reaction(
                    name=item.name,
                    reactants=reactants,
                    products=products,
                    reversible=item.reversible,
                )
            )

        pathway = Pathway(
            name=definition.name,
            description=definition.description,
            reactions=tuple(reactions),
        )

        return PathwayGraph.from_pathway(pathway)
